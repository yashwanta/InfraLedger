import {useState} from 'react';
import {api} from './api';
import {type Item} from './model';
import {AUTO_DIAGRAM_NAME,buildAutoDiagram,isAutoDiagram} from './AutoDiagram';

/** Creates or rebuilds the discovery-generated topology diagram for the selected organization. */
export function AutoDiagramButton({records,scope,onSaved,onOpen,onError}:{records:Item[];scope:string;onSaved:()=>Promise<void>;onOpen:(id:string)=>void;onError:(s:string)=>void}){
 const [busy,setBusy]=useState(false);
 const orgs=records.filter(r=>r.type==='organizations');
 const orgId=scope||orgs[0]?.id||'';
 const existing=records.find(r=>r.type==='diagrams'&&r.orgId===orgId&&isAutoDiagram(r));
 async function build(){
  setBusy(true);
  try{
   const {nodes,edges}=buildAutoDiagram(records,orgId);
   if(!nodes.length)throw new Error('No discovered devices to draw yet. Run discovery first.');
   const body={name:AUTO_DIAGRAM_NAME,orgId,diagramType:'Network topology',autoGenerated:true,description:'Built automatically from discovery and SNMP switch-port data. Rebuild it to pick up changes; edits to this diagram are replaced on rebuild.',nodes,edges};
   const saved=existing?await api<Item>('/records/'+existing.id,'PUT',{...existing,...body}):await api<Item>('/records','POST',{type:'diagrams',...body});
   await onSaved();
   onOpen(saved.id);
  }catch(e){onError((e as Error).message)}finally{setBusy(false)}
 }
 if(!orgId)return null;
 return <button disabled={busy} title="Draws the network from discovery: Internet, gateway, subnets, switches and devices." onClick={build}>{busy?'Building…':existing?'Rebuild from discovery':'Build from discovery'}</button>;
}
